function createPdf(stock?: typeof stocks[number]) {
  const selected = stock ? [stock] : stocks
  const title = stock ? `${stock.ticker} Investment Analysis` : 'InvestPI Investment Analysis'
  const lines = [
    title,
    'Generated by InvestPI',
    '',
    'Source: The AI Investment Opportunity of a Lifetime',
    'Channel: Market Insights',
    '',
    ...selected.flatMap((item) => [
      `${item.name} (${item.ticker}) — Score ${item.score}/10`,
      `Price ${item.price} | Daily change ${item.change}`,
      ...markers.map(([label, rating, detail]) => `${label}: ${rating} — ${detail}`),
      '',
    ]),
    'This report is for informational purposes only and is not financial advice.',
  ]
  const escaped = lines.map((line) => line.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)'))
  const content = `BT /F1 11 Tf 54 760 Td 15 TL ${escaped.map((line, index) => `${index ? 'T* ' : ''}(${line}) Tj`).join(' ')} ET`
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ]
  let pdf = '%PDF-1.4\n'
  const offsets = [0]
  objects.forEach((object, i) => {
    offsets.push(pdf.length)
    pdf += `${i + 1} 0 obj\n${object}\nendobj\n`
  })
  const xref = pdf.length
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n${offsets.slice(1).map((offset) => `${String(offset).padStart(10, '0')} 00000 n `).join('\n')}\n`
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`
  const url = URL.createObjectURL(new Blob([pdf], { type: 'application/pdf' }))
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = stock ? `InvestPI-${stock.ticker}-analysis.pdf` : 'InvestPI-analysis.pdf'
  anchor.click()
  URL.revokeObjectURL(url)
}

